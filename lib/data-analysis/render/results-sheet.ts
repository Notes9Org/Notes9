/**
 * The result, written back into the workbook as its own sheet.
 *
 * A statistic that lives only in a panel on screen is lost the moment the file
 * leaves the product: the collaborator who opens the .xlsx gets the numbers the
 * analysis was run ON, and none of the numbers it produced. Putting the result
 * in the workbook means the data and its analysis travel together, and it is
 * the same object the user already knows how to read, sort and paste.
 *
 * It is a REPORT, not an input. Nothing reads these cells back: they are
 * regenerated from the engine result every time, so editing them changes
 * nothing and cannot feed a number back into the analysis. That one-way flow is
 * what keeps Law 2 intact — the sheet is a rendering of the result, exactly as
 * the figure is.
 */

import type { AnalysisSpec } from "@/lib/data-analysis/spec/analysis-spec"
import type { EngineResult } from "@/lib/data-analysis/engine/contract"
import { EFFECT_LABEL } from "@/lib/data-analysis/provenance"

/** The name the results sheet takes in the workbook. */
export const RESULTS_SHEET_NAME = "Statistics"

type Cell = string | number | null

function p(value: number | null): Cell {
  if (value === null || !Number.isFinite(value)) return null
  // Kept as a number so the cell can be formatted, sorted and compared in the
  // spreadsheet. A string like "< 0.0001" would be none of those things.
  return value
}

/**
 * Build the rows of the statistics sheet.
 *
 * Returned as an array-of-arrays so the caller can hand it straight to SheetJS
 * without this module depending on a spreadsheet library.
 */
export function buildResultsSheet(
  spec: AnalysisSpec,
  result: EngineResult | null,
  options: { analysisName?: string } = {}
): Cell[][] {
  const rows: Cell[][] = []
  const blank = () => rows.push([])
  const section = (title: string) => {
    blank()
    rows.push([title])
  }

  rows.push([options.analysisName ?? spec.figure.title ?? "Analysis"])
  rows.push(["Generated by", result?.engineVersion ?? "not yet computed"])
  if (result) {
    rows.push(["Computed at", result.computedAt])
    rows.push(["Data version", result.dataVersionHash])
    rows.push(["Spec hash", result.specHash])
  }

  if (!result) {
    section("No result yet")
    rows.push(["Run the analysis to fill this sheet."])
    return rows
  }

  const ciPct = `${+((1 - spec.analysis.alpha) * 100).toFixed(4)}%`

  /* ── The headline ──────────────────────────────────────────────────────── */
  if (result.test) {
    const t = result.test
    section("Result")
    rows.push(["Test", t.test])
    if (t.statistic !== null) rows.push(["Statistic", t.statistic])
    if (t.df !== null) rows.push(["df", typeof t.df === "number" ? t.df : String(t.df)])
    rows.push(["p-value", p(t.pValue)])
    rows.push(["alpha", spec.analysis.alpha])
    rows.push(["Significant at alpha", t.pValue !== null ? (t.pValue < spec.analysis.alpha ? "yes" : "no") : "—"])
    rows.push(["Reported as", t.reportSentence])

    if (t.effectSizes.length > 0) {
      section("Effect size")
      rows.push(["Measure", "Term", "Value", `${ciPct} CI low`, `${ciPct} CI high`])
      for (const e of t.effectSizes) {
        rows.push([EFFECT_LABEL[e.name] ?? e.name, e.term ?? null, e.value, e.ciLow, e.ciHigh])
      }
    }

    if (t.terms.length > 0) {
      section("Model terms")
      rows.push(["Term", "Estimate", `${ciPct} CI low`, `${ciPct} CI high`, "Statistic", "df", "p"])
      for (const term of t.terms) {
        rows.push([
          term.term,
          term.estimate,
          term.ciLow,
          term.ciHigh,
          term.statistic,
          term.df === null ? null : typeof term.df === "number" ? term.df : String(term.df),
          p(term.pValue),
        ])
      }
    }

    if (t.assumptions.length > 0) {
      section("Assumption checks")
      rows.push(["Check", "Statistic", "p", "Passed", "Verdict", "Alternative"])
      for (const a of t.assumptions) {
        rows.push([a.name, a.statistic, p(a.pValue), a.passed ? "yes" : "no", a.verdict, a.alternative])
      }
    }

    if (t.pairwise.length > 0) {
      section(`Pairwise comparisons (${t.pairwise[0].correctionMethod})`)
      rows.push([
        "Group A",
        "Group B",
        "Difference of means",
        `${ciPct} CI low`,
        `${ciPct} CI high`,
        "p",
        "Adjusted p",
        "Significant",
      ])
      for (const c of t.pairwise) {
        rows.push([
          c.groupA,
          c.groupB,
          c.meanDifference,
          c.ciLow,
          c.ciHigh,
          p(c.pValue),
          p(c.pAdjusted),
          c.significant ? "yes" : "no",
        ])
      }
    }

    const sizes = Object.entries(t.groupSizes)
    if (sizes.length > 0) {
      section("Group sizes")
      rows.push(["Group", "n"])
      for (const [group, n] of sizes) rows.push([group, n])
    }
  }

  /* ── Descriptives ──────────────────────────────────────────────────────── */
  if (result.descriptives.length > 0) {
    section("Descriptive statistics")
    rows.push([
      "Column",
      "Group",
      "n",
      "Mean",
      "SD",
      "SEM",
      "Median",
      "Q1",
      "Q3",
      "IQR",
      "Min",
      "Max",
      "CV",
      "Geometric mean",
      "Skewness",
      "Kurtosis",
      "95% CI low",
      "95% CI high",
    ])
    for (const d of result.descriptives) {
      rows.push([
        d.column,
        d.group,
        d.n,
        d.mean,
        d.sd,
        d.sem,
        d.median,
        d.q1,
        d.q3,
        d.iqr,
        d.min,
        d.max,
        d.cv,
        d.geometricMean,
        d.skewness,
        d.kurtosis,
        d.ci95Low,
        d.ci95High,
      ])
    }
  }

  /* ── Curve fit ─────────────────────────────────────────────────────────── */
  if (result.curveFit) {
    const f = result.curveFit
    section(`Curve fit (${f.model})`)
    rows.push(["Parameter", "Value", "Std. error", "CI low", "CI high"])
    for (const [name, param] of Object.entries(f.parameters)) {
      rows.push([name, param.value, param.stderr, param.ciLow, param.ciHigh])
    }
    blank()
    rows.push(["EC50", f.ec50])
    rows.push(["R squared", f.rSquared])
    rows.push(["Adjusted R squared", f.adjustedRSquared])
    rows.push(["AICc", f.aicc])
    rows.push(["Sy.x", f.syx])
    rows.push(["Converged", f.converged ? "yes" : "no"])

    if (f.interpolated && f.interpolated.length > 0) {
      section("Interpolated unknowns")
      rows.push(["Label", "Signal", "Concentration", "Within standard range"])
      for (const u of f.interpolated) {
        rows.push([u.label, u.signal, u.concentration, u.inRange ? "yes" : "no"])
      }
    }
  }

  /* ── Survival ──────────────────────────────────────────────────────────── */
  if (result.survival) {
    for (const curve of result.survival.groups) {
      section(`Kaplan-Meier: ${curve.label}`)
      rows.push(["n", curve.n, "Events", curve.events, "Median survival", curve.median])
      rows.push(["Time", "Survival", "95% CI low", "95% CI high", "At risk"])
      for (let i = 0; i < curve.time.length; i++) {
        rows.push([curve.time[i], curve.survival[i], curve.lower[i], curve.upper[i], curve.atRisk[i]])
      }
    }
  }

  /* ── Exclusions and warnings ───────────────────────────────────────────── */
  if (spec.exclusions.length > 0) {
    // §8.1: an exported analysis must disclose its exclusions. A results sheet
    // that omitted them would be the exact omission the governance prevents.
    section("Excluded points")
    rows.push(["Row", "Reason", "Detail", "Method", "Excluded by", "When"])
    for (const e of spec.exclusions) {
      rows.push([
        e.rowId,
        e.reasonKind,
        e.reasonText,
        // A statistical exclusion must name its method and parameters, so
        // "outlier" can never be ad hoc.
        e.method
          ? `${e.method.name} (${Object.entries(e.method.params)
              .map(([k, v]) => `${k} ${v}`)
              .join(", ")})`
          : null,
        e.excludedBy,
        e.excludedAt,
      ])
    }
  }

  // A failed run has no numbers to report, so the sheet must say so outright.
  // Left among the warnings it read as a caveat on a result that never existed.
  if (result.error) {
    section("Error")
    rows.push(["Analysis", result.error.test])
    rows.push([result.error.message])
  }

  if (result.warnings.length > 0) {
    section("Warnings")
    for (const w of result.warnings) rows.push([w])
  }

  /* ── How it was produced ───────────────────────────────────────────────── */
  section("Method")
  rows.push(["Test requested", spec.analysis.test])
  // The engine substitutes when the request does not fit the data. Recording
  // only the request would credit the numbers to a test nobody ran.
  if (result.testRan && result.testRan !== spec.analysis.test) {
    rows.push(["Test performed", result.testRan])
  }
  rows.push(["Post-hoc correction", spec.analysis.postHoc])
  rows.push(["Tails", spec.analysis.tails])
  rows.push(["Missing values", spec.analysis.missingValues])
  if (spec.transforms.length > 0) {
    rows.push(["Transforms, in order", spec.transforms.map((t) => t.kind).join(" then ")])
  }
  if (spec.filters.length > 0) {
    rows.push(["Filters", spec.filters.map((f) => `${f.column} ${f.op} ${String(f.value)}`).join("; ")])
  }
  rows.push(["Source file", spec.dataset.fileName])
  if (spec.dataset.sheet) rows.push(["Source sheet", spec.dataset.sheet])

  return rows
}

/** Column widths that make the sheet readable without hand-resizing. */
export function resultsSheetColumnWidths(rows: Cell[][]): { wch: number }[] {
  const widest: number[] = []
  for (const row of rows) {
    for (const [i, cell] of row.entries()) {
      const len = cell === null || cell === undefined ? 0 : String(cell).length
      widest[i] = Math.max(widest[i] ?? 0, Math.min(len, 60))
    }
  }
  return widest.map((w) => ({ wch: Math.max(10, w + 2) }))
}
